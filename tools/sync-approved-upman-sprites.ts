import { createHash } from "node:crypto";
import { mkdir, readFile, rename, stat, writeFile } from "node:fs/promises";
import path from "node:path";

import { PrismaPg } from "@prisma/adapter-pg";
import { PrismaClient } from "@/app/generated/prisma/client";
import { validateUpmanPngBytes } from "@/lib/png-validation";

const MAX_BYTES = 4 * 1024 * 1024;
const DEFAULT_OBS_ROOT = "C:\\Users\\uprea\\Desktop\\UPMANDEX-OBS";
const MANIFEST_FILE = ".upmandex-approved-submissions.json";
const SPRITE_LIST_FILE = "approved-submissions.js";
// Legacy public store verified from approved Anniversary submissions. Add a new
// hostname through UPMANDEX_APPROVED_SUBMISSION_BLOB_HOSTS only after verifying it.
const VERIFIED_SUBMISSION_BLOB_HOSTS = ["e4pburhj5wrv8agh.public.blob.vercel-storage.com"];

type ManagedSprite = {
  slug: string;
  url: string;
  sha256: string;
  width: number;
  height: number;
};

type Manifest = {
  version: 1;
  generatedAt: string;
  entries: Record<string, ManagedSprite>;
};

process.loadEnvFile(".env.local");

function fail(message: string): never {
  throw new Error(`UPMANDEX approved-sprite sync: ${message}`);
}

function isSafeSlug(value: string) {
  return /^[a-z0-9-]+$/.test(value);
}

function isAllowedSubmissionUrl(value: string, trustedHosts: Set<string>) {
  try {
    const url = new URL(value);
    return (
      url.protocol === "https:" &&
      trustedHosts.has(url.hostname) &&
      url.username === "" &&
      url.password === "" &&
      url.port === "" &&
      url.search === "" &&
      url.hash === "" &&
      /^\/upman-submissions\/[a-z0-9]+\/[0-9a-f-]{36}\.png$/i.test(url.pathname)
    );
  } catch {
    return false;
  }
}

async function readManifest(file: string): Promise<Manifest> {
  try {
    const parsed: unknown = JSON.parse(await readFile(file, "utf8"));
    if (!parsed || typeof parsed !== "object") return { version: 1, generatedAt: "", entries: {} };
    const value = parsed as Partial<Manifest>;
    if (value.version !== 1 || !value.entries || typeof value.entries !== "object") return { version: 1, generatedAt: "", entries: {} };
    return { version: 1, generatedAt: typeof value.generatedAt === "string" ? value.generatedAt : "", entries: value.entries };
  } catch (error: unknown) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return { version: 1, generatedAt: "", entries: {} };
    fail("the existing local manifest is unreadable");
  }
}

async function exists(file: string) {
  try {
    await stat(file);
    return true;
  } catch (error: unknown) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return false;
    throw error;
  }
}

async function atomicWrite(file: string, bytes: Uint8Array | string) {
  const temporary = `${file}.${process.pid}.tmp`;
  await writeFile(temporary, bytes);
  await rename(temporary, file);
}

function spriteList(entries: Record<string, ManagedSprite>) {
  const filenames = Object.values(entries)
    .map((entry) => `${entry.slug}.png`)
    .filter((filename) => /^[a-z0-9-]+\.png$/.test(filename))
    .sort();
  return `/* Generated by tools/sync-approved-upman-sprites.ts. Do not edit manually. */\nwindow.UPMANDEX_APPROVED_UPMAN_SPRITES = Object.freeze(${JSON.stringify(filenames)});\n`;
}

async function downloadPng(url: string) {
  const response = await fetch(url, { redirect: "error" });
  if (!response.ok) fail(`image download failed with HTTP ${response.status}`);
  const contentType = response.headers.get("content-type")?.toLowerCase() ?? "";
  if (!contentType.startsWith("image/png")) fail("downloaded image did not declare image/png");
  const contentLength = Number(response.headers.get("content-length"));
  if (Number.isFinite(contentLength) && contentLength > MAX_BYTES) fail("downloaded image exceeds 4 MiB");
  const bytes = new Uint8Array(await response.arrayBuffer());
  if (!bytes.length || bytes.length > MAX_BYTES) fail("downloaded image exceeds 4 MiB or is empty");
  const image = validateUpmanPngBytes(bytes);
  if (!image) fail("downloaded image is not a valid supported PNG");
  return { bytes, ...image };
}

async function main() {
  const databaseUrl = process.env.DATABASE_URL;
  if (!databaseUrl) fail("DATABASE_URL is missing from .env.local");

  const obsRoot = process.env.UPMANDEX_OBS_ROOT || DEFAULT_OBS_ROOT;
  const spriteDirectory = path.join(obsRoot, "assets", "upmans");
  const manifestPath = path.join(spriteDirectory, MANIFEST_FILE);
  const spriteListPath = path.join(spriteDirectory, SPRITE_LIST_FILE);
  const configuredHosts = (process.env.UPMANDEX_APPROVED_SUBMISSION_BLOB_HOSTS ?? "")
    .split(",")
    .map((host) => host.trim().toLowerCase())
    .filter((host) => /^[a-z0-9-]+\.public\.blob\.vercel-storage\.com$/.test(host));
  const trustedHosts = new Set([...VERIFIED_SUBMISSION_BLOB_HOSTS, ...configuredHosts]);
  await mkdir(spriteDirectory, { recursive: true });

  const manifest = await readManifest(manifestPath);
  const prisma = new PrismaClient({ adapter: new PrismaPg({ connectionString: databaseUrl }) });

  try {
    const eligible = await prisma.upman.findMany({
      where: {
        dexVisibility: "PUBLIC",
        isPullable: true,
        sourceSubmission: { is: { status: "APPROVED" } },
      },
      select: { slug: true, image: true },
      orderBy: { slug: "asc" },
    });

    let imported = 0;
    let unchanged = 0;
    let skippedExisting = 0;
    const nextEntries: Record<string, ManagedSprite> = { ...manifest.entries };

    for (const upman of eligible) {
      if (!isSafeSlug(upman.slug)) {
        console.warn(`Skipped invalid slug: ${upman.slug}`);
        continue;
      }
      if (!isAllowedSubmissionUrl(upman.image, trustedHosts)) {
        console.warn(`Skipped ${upman.slug}: image is not an approved public submission Blob URL.`);
        continue;
      }

      const destination = path.join(spriteDirectory, `${upman.slug}.png`);
      const previous = manifest.entries[upman.slug];
      if (await exists(destination)) {
        if (previous?.url === upman.image) {
          unchanged += 1;
          continue;
        }
        if (!previous) {
          skippedExisting += 1;
          console.warn(`Skipped ${upman.slug}: existing local sprite is not managed by this synchronizer.`);
          continue;
        }
      }

      const downloaded = await downloadPng(upman.image);
      const sha256 = createHash("sha256").update(downloaded.bytes).digest("hex");
      await atomicWrite(destination, downloaded.bytes);
      nextEntries[upman.slug] = { slug: upman.slug, url: upman.image, sha256, width: downloaded.width, height: downloaded.height };
      imported += 1;
      console.info(`Imported approved sprite: ${upman.slug}`);
    }

    const nextManifest: Manifest = { version: 1, generatedAt: new Date().toISOString(), entries: nextEntries };
    await atomicWrite(manifestPath, `${JSON.stringify(nextManifest, null, 2)}\n`);
    await atomicWrite(spriteListPath, spriteList(nextEntries));
    console.info(`Approved-sprite sync complete: ${imported} imported, ${unchanged} unchanged, ${skippedExisting} preserved.`);
  } finally {
    await prisma.$disconnect();
  }
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : "UPMANDEX approved-sprite sync failed.");
  process.exitCode = 1;
});
